
public class Mascota {
    // Clase para la mascota opcional del guerrero.
    private String nombre;
    private int lealtad;

    public Mascota(String nombre, int lealtad) {
        this.nombre = nombre;
        this.lealtad = lealtad;
    }

    public String getNombre() {
        return nombre;
    }

    public int getLealtad() {
        return lealtad;
    }
}
